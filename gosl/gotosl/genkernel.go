// GenKernelHeader returns the novel generated WGSL kernel code
// for given kernel, which goes at the top of the resulting file.
func (st *State) GenKernelHeader(sy *System, kn *Kernel) string {
	var b strings.Builder
	b.WriteString("// Code generated by \"gosl\"; DO NOT EDIT\n")
	fmt.Fprintf(&b, "// kernel: %s\n\n", kn.Name)

	for gi, gp := range sy.Groups {
		if gp.Doc != "" {
			fmt.Fprintf(&b, "// %s\n", gp.Doc)
		}
		str := "storage"
		if gp.Uniform {
			str = "uniform"
		}
		if gi == 0 && sy.NTensors > 0 {
			access := ", read"
			if gp.Uniform {
				access = ""
			}
			b.WriteString("@group(0) @binding(0)\n")
			fmt.Fprintf(&b, "var<%s%s> TensorStrides: array<u32>;\n", str, access)
		}
		for _, vr := range gp.Vars {
			_, isAtomic := kn.Atomics[vr.Name]
			_, isUsed := kn.VarsUsed[vr.Name]
			if !isUsed {
				continue
			}
			access := ", read_write"
			if vr.ReadOnly && !vr.ReadOrWrite {
				access = ", read"
			}
			if gp.Uniform {
				access = ""
			}
			if vr.Doc != "" {
				fmt.Fprintf(&b, "// %s\n", vr.Doc)
			}
			if vr.NBuffs <= 1 {
				fmt.Fprintf(&b, "@group(%d) @binding(%d)\n", vr.Group, vr.Binding)
				fmt.Fprintf(&b, "var<%s%s> %s: ", str, access, vr.Name)
				if isAtomic {
					fmt.Fprintf(&b, "array<atomic<%s>>;\n", vr.SLType())
				} else {
					fmt.Fprintf(&b, "array<%s>;\n", vr.SLType())
				}
				continue
			}
			vn := vr.Binding
			for bi := range vr.NBuffs {
				fmt.Fprintf(&b, "@group(%d) @binding(%d)\n", gi, vn)
				fmt.Fprintf(&b, "var<%s%s> %s%d: ", str, access, vr.Name, bi)
				fmt.Fprintf(&b, "array<%s>;\n", vr.SLType())
				vn++
			}
		}
	}

	b.WriteString("\nalias GPUVars = i32;\n\n") // gets included when iteratively processing enumgen.go

	b.WriteString("@compute @workgroup_size(64, 1, 1)\n")
	b.WriteString("fn main(@builtin(workgroup_id) wgid: vec3<u32>, @builtin(num_workgroups) nwg: vec3<u32>, @builtin(local_invocation_index) loci: u32) {\n")
	b.WriteString("\tlet idx = loci + (wgid.x + wgid.y * nwg.x + wgid.z * nwg.x * nwg.y) * 64;\n")
	fmt.Fprintf(&b, "\t%s(idx);\n", kn.Name)
	b.WriteString("}\n")
	b.WriteString(st.GenTensorFuncs(sy, kn))
	return b.String()
}

// GenTensorFuncs returns the generated WGSL code
// for indexing the tensors in given system.
func (st *State) GenTensorFuncs(sy *System, kn *Kernel) string {
	var b strings.Builder

	done := make(map[string]bool)

	for _, gp := range sy.Groups {
		for _, vr := range gp.Vars {
			_, isUsed := kn.VarsUsed[vr.Name]
			if !vr.Tensor || !isUsed {
				continue
			}
			if vr.NBuffs > 1 {
				b.WriteString(st.GenNBuffFuncs(sy, vr))
			}

			fn := vr.IndexFunc()
			if _, ok := done[fn]; ok {
				continue
			}
			done[fn] = true
			typ := "u32"
			fmt.Fprintf(&b, "\nfn %s(", fn)
			nd := vr.TensorDims
			for d := range nd {
				fmt.Fprintf(&b, "s%d: %s, ", d, typ)
			}
			for d := range nd {
				fmt.Fprintf(&b, "i%d: u32", d)
				if d < nd-1 {
					b.WriteString(", ")
				}
			}
			b.WriteString(") -> u32 {\n\treturn ")
			for d := range nd {
				fmt.Fprintf(&b, "s%d * i%d", d, d)
				if d < nd-1 {
					b.WriteString(" + ")
				}
			}
			b.WriteString(";\n}\n")
		}
	}
	return b.String()
}

// GenNBuffFuncs returns the generated WGSL code
// for accessing data in multi-buffer variables.
func (st *State) GenNBuffFuncs(sy *System, vr *Var) string {
	var b strings.Builder
	fmt.Fprintf(&b, "\nfn %sGet(ix: u32) -> %s {\n", vr.Name, vr.SLType())
	bsz := st.Config.MaxBufferSize / 4 // assume 4 bytes per
	fmt.Fprintf(&b, "\tlet ii = ix / %d;\n", bsz)
	b.WriteString("\tswitch ii {\n")
	for bi := range vr.NBuffs {
		if bi == vr.NBuffs-1 {
			b.WriteString("\tdefault: {\n")
		} else {
			fmt.Fprintf(&b, "\tcase u32(%d): {\n", bi)
		}
		if bi > 0 {
			fmt.Fprintf(&b, "\t\treturn %s%d[ix - %d];\n", vr.Name, bi, bsz*uint32(bi))
		} else {
			fmt.Fprintf(&b, "\t\treturn %s%d[ix];\n", vr.Name, bi)
		}
		b.WriteString("\t}\n")
	}
	b.WriteString("\t}\n}\n")

	methNames := []string{"Set", "SetAdd", "SetSub", "SetMul", "SetDiv"}
	methOps := []string{"=", "+=", "-=", "*=", "/="}
	for mi, mn := range methNames {
		mop := methOps[mi]
		fmt.Fprintf(&b, "\nfn %s%s(vl: %s, ix: u32) {\n", vr.Name, mn, vr.SLType())
		fmt.Fprintf(&b, "\tlet ii = ix / %d;\n", bsz)
		b.WriteString("\tswitch ii {\n")
		for bi := range vr.NBuffs {
			if bi == vr.NBuffs-1 {
				b.WriteString("\tdefault: {\n")
			} else {
				fmt.Fprintf(&b, "\tcase u32(%d): {\n", bi)
			}
			if bi > 0 {
				fmt.Fprintf(&b, "\t\t%s%d[ix - %d] %s vl;\n", vr.Name, bi, bsz*uint32(bi), mop)
			} else {
				fmt.Fprintf(&b, "\t\t%s%d[ix] %s vl;\n", vr.Name, bi, mop)
			}
			b.WriteString("\t}\n")
		}
		b.WriteString("\t}\n}\n")
	}

	return b.String()
}
